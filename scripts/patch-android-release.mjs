import { existsSync, readFileSync, writeFileSync } from 'node:fs';

// Capacitor generates android/ during CI. Keep app signing outside the public repo.
const path = 'android/app/build.gradle';
if (!existsSync(path)) throw new Error(`${path} was not generated by Capacitor`);
const source = readFileSync(path, 'utf8');
const marker = '// BEGIN APP-UI-DEMO FIXED-SIGNATURE RELEASE CONFIG';
if (!source.includes('com.android.application')) {
  throw new Error('Unexpected Android Gradle project: app plugin not found');
}
if (source.includes(marker)) {
  console.log('Fixed-signature release configuration already present');
  process.exit(0);
}

// The signing key and password are provided by protected CI secrets.
// Avoid committing either one into the source repository.
const addition = String.raw`

${marker}
def ciReleaseKeystorePath = System.getenv('ANDROID_RELEASE_KEYSTORE_PATH')
def ciReleasePassword = System.getenv('ANDROID_RELEASE_STORE_PASSWORD')
if (!ciReleaseKeystorePath || !ciReleasePassword) {
    throw new GradleException('Release signing secrets are missing; configure GitHub Actions repository secrets')
}
def ciReleaseBuildNumber = (System.getenv('GITHUB_RUN_NUMBER') ?: '1').toInteger()
android {
    defaultConfig {
        versionCode 10000 + ciReleaseBuildNumber
        versionName "0.6.\${ciReleaseBuildNumber}"
    }
    signingConfigs {
        ciRelease {
            storeFile file(ciReleaseKeystorePath)
            storePassword ciReleasePassword
            keyAlias 'kids-ui-demo-release'
            keyPassword ciReleasePassword
        }
    }
    buildTypes {
        release {
            signingConfig signingConfigs.ciRelease
        }
    }
}
// END APP-UI-DEMO FIXED-SIGNATURE RELEASE CONFIG
`;
writeFileSync(path, source + addition);
console.log('Configured fixed-signature Android release (secrets loaded only by Gradle)');
